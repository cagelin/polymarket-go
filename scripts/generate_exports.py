"""Generate canonical facade aliases from Go's AST; --check never modifies files."""
import argparse
import difflib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DIRECTORIES = ['models', 'errors', 'internal/clob', 'internal/gamma', 'internal/data',
               'internal/rfq', 'internal/trading', 'streams', 'rfq']


def generate():
    inventory = json.loads(subprocess.check_output(
        ['go', 'run', './scripts/exportinventory', *DIRECTORIES], cwd=ROOT))
    exports = [entry for entry in inventory if not (
        entry['Name'].endswith('Client') or
        entry['Directory'] in ['streams', 'internal/trading', 'rfq'] and entry['Name'] == 'Config')]
    exports.sort(key=lambda entry: entry['Name'])
    names = [('RFQ' if entry['Directory'] == 'rfq' else '') + entry['Name'] for entry in exports]
    if len(set(names)) != len(names):
        raise ValueError('duplicate public name')
    text = ('// Code generated by scripts/generate_exports.py; DO NOT EDIT.\n'
            '// Canonical public names; implementations live in domain packages.\n'
            '// This generated file remains subject to all repository linters.\n\npackage polymarket\n\nimport (\n')
    for directory in sorted({entry['Directory'] for entry in exports}):
        text += ('rfqsession ' if directory == 'rfq' else '') + '"github.com/cagelin/polymarket-go/' + directory + '"\n'
    text += '"github.com/cagelin/polymarket-go/transactions"\n"github.com/cagelin/polymarket-go/pagination"\n)\n'
    for entry in exports:
        name, directory, kind = entry['Name'], entry['Directory'], entry['Kind']
        public_name = ('RFQ' if directory == 'rfq' else '') + name
        package = 'rfqsession' if directory == 'rfq' else Path(directory).name
        text += (f'\n// {public_name} aliases {package}.{name}.\n'
                 f'{kind} {public_name}{entry["Parameters"].replace("rfq.", "rfqsession.") if directory == "rfq" else entry["Parameters"]} = {package}.{name}{entry["Arguments"]}\n')
    text += '''
// ErrUnsupportedStreamEvent identifies an unsupported upstream event variant.
var ErrUnsupportedStreamEvent = models.ErrUnsupportedStreamEvent
// TransactionHandle tracks on-chain submission and confirmation.
type TransactionHandle = transactions.Handle
// Page holds a batch of results and continuation metadata.
type Page[T any] = pagination.Page[T]
// Paginator lazily retrieves results.
type Paginator[T any] = pagination.Paginator[T]
// Asset selects one CLOB asset.
func Asset(id ClobAssetID) AssetQuery { return clob.Asset(id) }
'''
    return subprocess.check_output(['gofmt'], input=text.encode(), cwd=ROOT).decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    destination = ROOT / 'types.go'
    if args.check:
        existing = destination.read_text()
        if existing != generated:
            print(''.join(difflib.unified_diff(existing.splitlines(True), generated.splitlines(True),
                                             fromfile='types.go', tofile='generated types.go')), end='')
            raise SystemExit(1)
    else:
        destination.write_text(generated, newline="\n")


if __name__ == '__main__':
    main()
