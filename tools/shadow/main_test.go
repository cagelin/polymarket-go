package main

import (
	"go/ast"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"slices"
	"testing"
)

func TestFindShadows(t *testing.T) {
	cases := []struct {
		name   string
		source string
		want   []string
	}{
		{"nested error", `func f() { var err error; { err := 1; _ = err }; _ = err }`, []string{"err"}},
		{"range variable", `func f() { i := 1; for i := range 2 { _ = i }; _ = i }`, []string{"i"}},
		{"callback parameter", `func f() { value := 1; _ = func(value string) { _ = value }; _ = value }`, []string{"value"}},
		{"type switch", `func f(v any) { value := 1; switch value := v.(type) { case int: _ = value; case string: _ = value }; _ = value }`, []string{"value"}},
		{"package variable", `var value int; func f(value string) { _ = value }`, []string{"value"}},
		{"later package variable", `func f(value string) { _ = value }; var value int`, []string{"value"}},
		{"builtin", `func f(len int) { _ = len }`, []string{"len"}},
		{"type parameter", `func f[any int](v any) { _ = v }`, []string{"any"}},
		{"import name", `import "errors"; var _ = errors.New; func f(errors string) { _ = errors }`, []string{"errors"}},
		{"named result", `var result int; func f() (result string) { return }`, []string{"result"}},
		{"const and type", `var value int; func f() { const value = 1; _ = value }; func g() { type value int; var _ value }`, []string{"value", "value"}},
		{"self redeclaration", `func f() { value := 1; { value := value; _ = value } }`, []string{"value"}},
		{"same scope reuse", `func f() { var err error; value, err := 1, error(nil); _, _ = value, err }`, nil},
		{"separate scopes", `func f() { if value := 1; value > 0 {} ; if value := 2; value > 0 {} }`, nil},
		{"later local variable", `func f() { _ = func(value int) {}; value := 1; _ = value }`, nil},
		{"field and method", `var value int; type item struct { value int }; func (i item) valueMethod() {}`, nil},
		{"blank identifier", `func f() { var _ int; { var _ string } }`, nil},
		{"generated source", "// Code generated by fixture. DO NOT EDIT.\nfunc f() { value := 1; { value := 2; _ = value }; _ = value }", []string{"value"}},
	}
	for _, test := range cases {
		t.Run(test.name, func(subtest *testing.T) {
			files := token.NewFileSet()
			file, err := parser.ParseFile(files, "fixture.go", "package fixture\n"+test.source, parser.ParseComments)
			if err != nil {
				subtest.Fatal(err)
			}
			info := &types.Info{Defs: make(map[*ast.Ident]types.Object), Implicits: make(map[ast.Node]types.Object)}
			config := types.Config{Importer: importer.Default()}
			if _, err = config.Check("fixture", files, []*ast.File{file}, info); err != nil {
				subtest.Fatal(err)
			}
			var got []string
			for _, item := range findShadows(info) {
				got = append(got, item.name)
			}
			if !slices.Equal(got, test.want) {
				subtest.Errorf("findShadows(%q) = %v, want %v", test.source, got, test.want)
			}
		})
	}
}
